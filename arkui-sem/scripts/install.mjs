#!/usr/bin/env node
// Install (or remove) arkui-sem into an opencode project:
//   node scripts/install.mjs <project-dir>             → .opencode/plugins/arkui-sem.ts + .opencode/skills/arkui-state-management/
//   node scripts/install.mjs <project-dir> --uninstall
//   node scripts/install.mjs --global                  → ~/.config/opencode/{plugins,skills}/
//   node scripts/install.mjs <project-dir> --skill-only → skill without the plugin (the evaluation's control arm)
// The plugin file re-exports this checkout's dist/opencode.js: rebuild here, then restart opencode.
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const uninstall = args.includes("--uninstall");
const global = args.includes("--global");
const skillOnly = args.includes("--skill-only");
const project = args.find((a) => !a.startsWith("--"));

if (!global && !project) {
  console.error("usage: node scripts/install.mjs <project-dir> [--skill-only|--uninstall]  |  node scripts/install.mjs --global [--uninstall]");
  process.exit(2);
}

const base = global ? join(homedir(), ".config", "opencode") : join(resolve(project), ".opencode");
const pluginFile = join(base, "plugins", "arkui-sem.ts");
const skillDir = join(base, "skills", "arkui-state-management");
const entry = join(root, "dist", "opencode.js");

if (uninstall) {
  rmSync(pluginFile, { force: true });
  rmSync(skillDir, { recursive: true, force: true });
  console.log(`removed arkui-sem from ${base}`);
  process.exit(0);
}

if (skillOnly) {
  rmSync(pluginFile, { force: true });
  mkdirSync(skillDir, { recursive: true });
  copyFileSync(join(root, "skills", "arkui-state-management", "SKILL.md"), join(skillDir, "SKILL.md"));
  console.log(`installed the arkui-state-management skill only (no plugin) into ${base}`);
  process.exit(0);
}

if (!existsSync(entry)) {
  console.error(`missing ${entry}; run \`npm install && npm run build\` in ${root} first`);
  process.exit(1);
}

mkdirSync(dirname(pluginFile), { recursive: true });
writeFileSync(
  pluginFile,
  `// Generated by arkui-sem/scripts/install.mjs. Loads the plugin from its checkout.\nexport { ArkuiSemPlugin } from ${JSON.stringify(pathToFileURL(entry).href)}\n`,
);
mkdirSync(skillDir, { recursive: true });
copyFileSync(join(root, "skills", "arkui-state-management", "SKILL.md"), join(skillDir, "SKILL.md"));

console.log(`installed arkui-sem into ${base}
  plugin: ${pluginFile}
  skill:  ${join(skillDir, "SKILL.md")}
Restart opencode in that project. Backend: ARKUI_SEM_BACKEND=heuristic|jev|clef-flash|clef|deepseek-flash|laya (default clef).`);
